#!/usr/bin/env python3
"""
Builds supabase/import_json_levels.sql from data/_list.json + data/<level>.json.

Run from the repository root:
    python3 scripts/build_import_sql.py

The generated SQL is safe to run more than once: levels that already exist
(same path) and records that already exist (same player + level, accepted)
are skipped.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "supabase" / "import_json_levels.sql"

# invisible characters that sneaked into some links
INVISIBLE = re.compile(r"[​-‏⁠﻿]")
RATINGS = {"rate", "featured", "epic", "legendary", "mythic"}
DIFFICULTIES = {"easy", "medium", "hard", "insane", "extreme"}


def clean(value):
    return INVISIBLE.sub("", str(value)).strip()


def q(value):
    """SQL literal"""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    return "'" + clean(value).replace("'", "''") + "'"


def arr(values):
    return "array[" + ", ".join(q(v) for v in values) + "]::text[]" if values else "'{}'::text[]"


def url_or_none(value):
    v = clean(value or "")
    return v if re.match(r"^https?://", v, re.I) else None


def main():
    order = json.loads((DATA / "_list.json").read_text(encoding="utf-8"))
    levels, records, warnings = [], [], []

    for rank, path in enumerate(order, start=1):
        d = json.loads((DATA / f"{path}.json").read_text(encoding="utf-8"))
        rating = str(d.get("rating", "")).lower()
        difficulty = str(d.get("difficulty", "")).lower()
        verification = url_or_none(d.get("verification"))
        try:
            ptq = min(100, max(1, int(float(d.get("percentToQualify", 100)))))
        except (TypeError, ValueError):
            ptq = 100
        if not verification:
            warnings.append(f"{path}: verification is not a link, skipped level")
            continue
        levels.append(
            "    ("
            + ", ".join(
                [
                    q(path),
                    q(str(d["id"]) if d.get("id") not in (None, "") else None),
                    q((clean(d.get("name", "")) or path)[:64]),
                    q(d["author"][:48]),
                    # some JSON files have "A, B" as one creator -> split
                    arr([c.strip()[:48] for cs in d.get("creators", []) for c in str(cs).split(",") if c.strip()][:30]),
                    q(d["verifier"][:48]),
                    q(verification),
                    q(url_or_none(d.get("showcase"))),
                    q(d.get("password") or None),
                    q(rating if rating in RATINGS else None),
                    q(difficulty if difficulty in DIFFICULTIES else None),
                    str(rank),
                    str(ptq),
                ]
            )
            + ")"
        )
        seen = set()
        for r in d.get("records", []):
            user = clean(r.get("user", ""))[:48]
            link = url_or_none(r.get("link"))
            if not user or not link or user.lower() in seen:
                warnings.append(f"{path}: skipped record {r}")
                continue
            try:
                percent = int(float(r.get("percent", 100)))
            except (TypeError, ValueError):
                percent = 0
            if not 1 <= percent <= 100:
                warnings.append(f"{path}: skipped record with invalid percent {r}")
                continue
            seen.add(user.lower())
            hz = r.get("hz")
            cbf = isinstance(hz, str) and hz.upper() == "CBF" or bool(r.get("cbf"))
            if isinstance(hz, str) and hz.strip().isdigit():
                hz = int(hz.strip())
            hz = hz if isinstance(hz, int) and 1 <= hz <= 1000 else None
            records.append(
                "    ("
                + ", ".join(
                    [
                        q(user),
                        q(path),
                        q((clean(d.get("name", "")) or path)[:128]),
                        q(str(d["id"]) if d.get("id") not in (None, "") else None),
                        q(link),
                        q(percent),
                        q(hz),
                        q(bool(r.get("mobile"))),
                        q(cbf),
                    ]
                )
                + ")"
            )

    sql = f"""-- =====================================================================
-- MCCLL – import all levels and records from data/*.json into Supabase.
-- Generated by scripts/build_import_sql.py – do not edit by hand.
--
-- Run ONCE in Supabase: SQL Editor -> New query -> paste -> Run
-- (after supabase/schema.sql). Running it again does no harm:
-- existing levels and records are skipped.
--
-- {len(levels)} levels, {len(records)} records
-- =====================================================================

begin;

insert into public.levels
    (path, level_id, name, author, creators, verifier, verification,
     showcase, password, rating, difficulty, placement, percent_to_qualify)
values
{",\n".join(levels)}
on conflict (path) do nothing;

insert into public.submissions
    (player_name, level_path, level_name, level_id, video,
     percent, hz, mobile, cbf, status)
select v.player, v.level_path, v.level_name, v.level_id, v.video,
       v.percent, v.hz, v.mobile, v.cbf, 'accepted'
from (values
{",\n".join(records)}
) as v(player, level_path, level_name, level_id, video, percent, hz, mobile, cbf)
where not exists (
    select 1
    from public.submissions s
    left join public.profiles p on p.id = s.user_id
    where s.level_path = v.level_path
      and s.status = 'accepted'
      and lower(coalesce(p.username, s.player_name)) = lower(v.player)
);

-- levels added on the website before the import keep their spot
select public.renumber_levels();

commit;
"""
    OUT.write_text(sql, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(levels)} levels, {len(records)} records")
    for w in warnings:
        print("warning:", w)


if __name__ == "__main__":
    main()
